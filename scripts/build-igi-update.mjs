#!/usr/bin/env node
/**
 * The SQL that brings a live database from one seed to the next.
 *
 * The switch-on file only ever adds (ON CONFLICT DO NOTHING): right for an
 * empty database, useless for a correction. When Michael's next sheet changes
 * a past day's figure or the size of a run, this is what carries it: the
 * difference between the seed being replaced and the seed just built, as
 * statements that add what is new, correct what moved, and touch nothing
 * else — in particular nothing the app itself recorded.
 *
 *   node scripts/build-igi-update.mjs                      # HEAD's seed → working copy's seed
 *   node scripts/build-igi-update.mjs --from old-seed.json # an explicit starting point
 *
 * Writes database-migrations/igi-update-<as_of>.sql, with a check at the end
 * that shouts if the figures do not land where the seed says they should.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expectedFigures } from '../lib/igi/seedFromSheet.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const fromIdx = args.indexOf('--from');
const before = fromIdx >= 0
  ? JSON.parse(readFileSync(resolve(args[fromIdx + 1]), 'utf8'))
  : JSON.parse(execSync('git show HEAD:lib/igi/seed.json', { cwd: ROOT, encoding: 'utf8' }));
const after = JSON.parse(readFileSync(resolve(ROOT, 'lib/igi/seed.json'), 'utf8'));

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? 'NULL' : String(v));
const model = (serial) => `(SELECT id FROM public.igi_models WHERE serial = ${q(serial)})`;
const visit = (no) => `(SELECT id FROM public.igi_visits WHERE visit_no = ${n(no)})`;

const out = [];
const say = (...l) => out.push(...l);
let changes = 0;

say(
  '-- ═══════════════════════════════════════════════════════════════════════',
  `--  LoveLab × IGI — bring the database from ${before.as_of} to ${after.as_of}`,
  '-- ═══════════════════════════════════════════════════════════════════════',
  '--',
  `--  Generated by scripts/build-igi-update.mjs from lib/igi/seed.json — do not edit by hand.`,
  '--  Adds what the new sheet has, corrects what it changed, leaves the rest.',
  '--  Safe to run twice. Nothing recorded by the app itself is touched.',
  '',
  'BEGIN;',
  '',
);

// ── Models: quantity ordered ────────────────────────────────────────────────
const bm = new Map(before.models.filter((m) => m.serial).map((m) => [m.serial, m]));
say('-- Quantities ordered that moved in IGI\'s file');
for (const m of after.models.filter((x) => x.serial)) {
  const p = bm.get(m.serial);
  if (!p) { say(`-- ${m.serial} is new: run the switch-on file for new models first.`); continue; }
  if (p.qty_ordered !== m.qty_ordered) {
    changes++;
    say(`UPDATE public.igi_models SET qty_ordered = ${n(m.qty_ordered)}, updated_at = now() WHERE serial = ${q(m.serial)};  -- ${m.name}: ${p.qty_ordered ?? 'none'} → ${m.qty_ordered ?? 'none'}`);
  }
  // A reserved serial IGI have since produced goes into use. Locked to the
  // state it is leaving, so a model someone moved on since is not moved back.
  if (p.state !== m.state) {
    changes++;
    say(`UPDATE public.igi_models SET state = ${q(m.state)}, updated_at = now() WHERE serial = ${q(m.serial)} AND state = ${q(p.state)};  -- ${m.name}: ${p.state} → ${m.state}`);
  }
}
say('');

// ── Batches: the opening run, resized ───────────────────────────────────────
const bb = new Map(before.batches.map((b) => [b.serial, b]));
say('-- Opening runs whose size changed');
for (const b of after.batches) {
  const p = bb.get(b.serial);
  if (!p) {
    changes++;
    say(`INSERT INTO public.igi_batches (model_id, qty, batch_date, reference)`,
        `  SELECT ${model(b.serial)}, ${n(b.qty)}, ${q(b.batch_date)}, ${q(b.reference)}`,
        `  WHERE NOT EXISTS (SELECT 1 FROM public.igi_batches WHERE model_id = ${model(b.serial)} AND reference = ${q(b.reference)});`);
  } else if (p.qty !== b.qty) {
    changes++;
    say(`UPDATE public.igi_batches SET qty = ${n(b.qty)} WHERE model_id = ${model(b.serial)} AND reference = ${q(b.reference)};  -- ${b.serial}: ${p.qty} → ${b.qty}`);
  }
}
say('');

// ── Movements ───────────────────────────────────────────────────────────────
const bv = new Map(before.visits.map((v) => [v.visit_no, v]));
say('-- Movements: new days, and corrected figures on days already recorded');
for (const v of after.visits) {
  const p = bv.get(v.visit_no);
  if (!p) {
    changes++;
    say(`-- V-${String(v.visit_no).padStart(3, '0')} ${v.visit_date}: ${v.lines.length} line(s), ${v.lines.reduce((t, l) => t + l.qty, 0) || v.unattributed_total} certificates`);
    say(`INSERT INTO public.igi_visits (visit_no, visit_date, status, date_suspect, unattributed_total, closed_at)`,
        `  VALUES (${n(v.visit_no)}, ${q(v.visit_date)}, ${q(v.status)}, ${v.date_suspect}, ${n(v.unattributed_total)}, ${q(`${v.visit_date}T12:00:00Z`)})`,
        `  ON CONFLICT (visit_no) DO NOTHING;`);
    for (const l of v.lines) {
      say(`INSERT INTO public.igi_visit_lines (visit_id, model_id, qty_requested, qty_issued, qty_received)`,
          `  VALUES (${visit(v.visit_no)}, ${model(l.serial)}, ${n(l.qty)}, ${n(l.qty)}, ${n(l.qty)})`,
          `  ON CONFLICT (visit_id, model_id) DO NOTHING;`);
    }
    say('');
    continue;
  }
  if (p.visit_date !== v.visit_date || p.unattributed_total !== v.unattributed_total) {
    changes++;
    say(`UPDATE public.igi_visits SET visit_date = ${q(v.visit_date)}, unattributed_total = ${n(v.unattributed_total)} WHERE visit_no = ${n(v.visit_no)};`);
  }
  const pl = new Map(p.lines.map((l) => [l.serial, l.qty]));
  for (const l of v.lines) {
    const was = pl.get(l.serial);
    if (was === undefined) {
      changes++;
      say(`INSERT INTO public.igi_visit_lines (visit_id, model_id, qty_requested, qty_issued, qty_received)`,
          `  VALUES (${visit(v.visit_no)}, ${model(l.serial)}, ${n(l.qty)}, ${n(l.qty)}, ${n(l.qty)})`,
          `  ON CONFLICT (visit_id, model_id) DO NOTHING;  -- V-${String(v.visit_no).padStart(3, '0')} ${v.visit_date} ${l.serial}: new line`);
    } else if (was !== l.qty) {
      changes++;
      say(`UPDATE public.igi_visit_lines SET qty_requested = ${n(l.qty)}, qty_issued = ${n(l.qty)}, qty_received = ${n(l.qty)}`,
          `  WHERE visit_id = ${visit(v.visit_no)} AND model_id = ${model(l.serial)};  -- V-${String(v.visit_no).padStart(3, '0')} ${v.visit_date} ${l.serial}: ${was} → ${l.qty}`);
    }
  }
  for (const [serial, was] of pl) {
    if (!v.lines.find((l) => l.serial === serial)) {
      changes++;
      say(`DELETE FROM public.igi_visit_lines WHERE visit_id = ${visit(v.visit_no)} AND model_id = ${model(serial)};  -- V-${String(v.visit_no).padStart(3, '0')} ${serial}: ${was} → 0`);
    }
  }
}
say('');

// ── The check ───────────────────────────────────────────────────────────────
const exp = expectedFigures(after);
say(
  '-- ── The figures must land where the seed says. Only imported movements',
  '-- ── (created_by IS NULL) are counted: the app\'s own are not the sheet\'s.',
  'DO $$',
  'DECLARE',
  '  ordered bigint; attributed bigint; unattributed bigint; movements bigint;',
  'BEGIN',
  "  SELECT coalesce(sum(qty),0) INTO ordered FROM public.igi_batches WHERE reference = 'initial order';",
  '  SELECT coalesce(sum(l.qty_issued),0) INTO attributed FROM public.igi_visit_lines l JOIN public.igi_visits v ON v.id = l.visit_id WHERE v.created_by IS NULL;',
  '  SELECT coalesce(sum(unattributed_total),0) INTO unattributed FROM public.igi_visits WHERE created_by IS NULL;',
  '  SELECT count(*) INTO movements FROM public.igi_visits WHERE created_by IS NULL;',
  `  IF ordered <> ${exp['certificates ordered']} THEN RAISE EXCEPTION 'certificates ordered: % (expected ${exp['certificates ordered']})', ordered; END IF;`,
  `  IF attributed <> ${exp['issued with a model']} THEN RAISE EXCEPTION 'issued with a model: % (expected ${exp['issued with a model']})', attributed; END IF;`,
  `  IF unattributed <> ${exp['issued with no model']} THEN RAISE EXCEPTION 'issued with no model: % (expected ${exp['issued with no model']})', unattributed; END IF;`,
  `  IF movements <> ${exp.movements} THEN RAISE EXCEPTION 'movements from IGI''s file: % (expected ${exp.movements})', movements; END IF;`,
  `  RAISE NOTICE 'IGI figures as of ${after.as_of}: ordered %, issued with a model %, without %, movements % — all as expected', ordered, attributed, unattributed, movements;`,
  'END $$;',
  '',
  'COMMIT;',
  '',
);

const file = `database-migrations/igi-update-${after.as_of}.sql`;
writeFileSync(resolve(ROOT, file), out.join('\n'));
console.log(`Wrote ${file} — ${changes} change(s), ${out.length} lines, ${before.as_of} → ${after.as_of}.`);
