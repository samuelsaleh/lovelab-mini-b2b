#!/usr/bin/env node
/**
 * Builds database-migrations/igi-switch-on.sql — the one file that turns the
 * certificate module on.
 *
 * Everything the module needs, in one paste into the Supabase SQL editor:
 * the tables, the opening balances from IGI's file, one shelf reading so the
 * screens are populated from the first minute, and a check at the end that
 * shouts if any figure is wrong.
 *
 * Generated rather than hand-written so it cannot drift from lib/igi/seed.json.
 *
 *   node scripts/build-igi-switch-on.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(resolve(ROOT, p), 'utf8');

const seed = JSON.parse(read('lib/igi/seed.json'));
const renames = JSON.parse(read('lib/igi/modelRenames.json'));
const live = JSON.parse(read('lib/__tests__/fixtures/packing-stock-2026-08-28.json'));
const SHELF_DATE = '2026-08-28';   // the day the reading below was captured

/** Single-quoted SQL literal, or NULL. */
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
/** Numeric literal, or NULL. */
const n = (v) => (v === null || v === undefined ? 'NULL' : String(v));
/** A model id looked up by its serial. */
const model = (serial) => `(SELECT id FROM public.igi_models WHERE serial = ${q(serial)})`;

const out = [];
const say = (...lines) => out.push(...lines);

// ── Header ──────────────────────────────────────────────────────────────────
say(
  '-- ═══════════════════════════════════════════════════════════════════════',
  '--  LoveLab × IGI — switch the certificate module on',
  '-- ═══════════════════════════════════════════════════════════════════════',
  '--',
  '--  Paste this whole file into the Supabase SQL editor and run it.',
  '--',
  '--  It does three things:',
  '--    1. creates the tables the certificate screens read from, and sets out',
  '--       exactly what IGI may and may not do once they have a login',
  '--    2. loads the opening balances from IGI\'s file, 27 August 2026',
  '--    3. checks every figure and STOPS if any of them is wrong',
  '--',
  '--  A successful run ends with:  IGI: ALL FIGURES MATCH',
  '--  Anything else means nothing was saved — the whole run is one transaction.',
  '--',
  '--  Running it twice is safe. It corrects rather than duplicates.',
  '--',
  `--  Generated by scripts/build-igi-switch-on.mjs — do not edit by hand.`,
  '',
  'BEGIN;',
  '',
);

// ── 1. The tables ───────────────────────────────────────────────────────────
say(
  '-- ─── 1 of 3 · The tables ───────────────────────────────────────────────',
  '',
  read('supabase/migrations/20260828120000_igi_certificates.sql').trimEnd(),
  '',
  read('supabase/migrations/20260828140000_igi_visit_authorship.sql').trimEnd(),
  '',
  read('supabase/migrations/20260828160000_igi_portal_writes.sql').trimEnd(),
  '',
  read('supabase/migrations/20260828180000_igi_invoices.sql').trimEnd(),
  '',
  read('supabase/migrations/20260910120000_igi_new_models.sql').trimEnd(),
  '',
  read('supabase/migrations/20260910140000_igi_order_min.sql').trimEnd(),
  '',
);

// ── 2. The opening balances ─────────────────────────────────────────────────
say(
  '-- ─── 2 of 3 · The opening balances ─────────────────────────────────────',
  '--',
  '-- IGI\'s file as of 27 August 2026. Keyed on the serial, the movement number',
  '-- and the description, so a second run changes nothing.',
  '',
  '-- Models that IGI have numbered.',
);

const numbered = seed.models.filter((m) => m.serial);
say('INSERT INTO public.igi_models');
say('  (serial, serial_full, name, igi_name, stones, carat, shape, spec, state, qty_ordered, sort_order)');
say('VALUES');
say(numbered.map((m) => `  (${[
  q(m.serial), q(m.serial_full), q(m.name), q(m.igi_name), q(m.stones),
  n(m.carat), q(m.shape), q(m.spec), q(m.state), n(m.qty_ordered), n(m.sort_order),
].join(', ')})`).join(',\n'));
// The unique index on serial is partial (models awaiting one have none), so the
// conflict target has to carry the same predicate.
say('ON CONFLICT (serial) WHERE serial IS NOT NULL DO NOTHING;', '');

say('-- Models LoveLab have asked for that IGI have not numbered yet.');
for (const m of seed.models.filter((x) => !x.serial)) {
  say(
    'INSERT INTO public.igi_models (name, stones, carat, shape, spec, state, sort_order)',
    `SELECT ${[q(m.name), q(m.stones), n(m.carat), q(m.shape), q(m.spec), q(m.state), n(m.sort_order)].join(', ')}`,
    // Any state: once IGI have numbered it, it is in use under the same name
    // and carat, and must not come back as a second model waiting for a serial.
    'WHERE NOT EXISTS (',
    `  SELECT 1 FROM public.igi_models`,
    `   WHERE name = ${q(m.name)} AND carat = ${n(m.carat)}`,
    ');',
  );
}
say('');

// Names LoveLab changed after the first switch-on. A fresh database gets the
// new names from the INSERT above; one that already holds the old ones is
// corrected here — and only where the old name is still in place, so a name
// somebody has since edited on the Models screen is left alone.
say(
  '-- Model names as LoveLab write them (11 Sept 2026). Only rows still carrying',
  '-- the earlier name are touched.',
);
for (const r of renames.renames) {
  say(`UPDATE public.igi_models SET name = ${q(r.to)} WHERE serial = ${q(r.serial)} AND name = ${q(r.from)};`);
}
say('');

say(
  '-- Every description LoveLab\'s own software returns, classified once so the',
  '-- "needs a human" queue starts empty.',
  'INSERT INTO public.igi_descriptions (description, model_id, kind)',
  'VALUES',
);
say(seed.descriptions.map((d) => `  (${q(d.description)}, ${d.serial ? model(d.serial) : 'NULL'}, ${q(d.kind)})`).join(',\n'));
say('ON CONFLICT (description) DO NOTHING;', '');

say(
  '-- The original commissioned run, one batch per model. IGI\'s stock is the sum',
  '-- of these, so nothing is ever overwritten.',
);
for (const b of seed.batches) {
  say(
    'INSERT INTO public.igi_batches (model_id, qty, batch_date, reference)',
    `SELECT ${model(b.serial)}, ${b.qty}, ${q(b.batch_date)}, ${q(b.reference)}`,
    `WHERE NOT EXISTS (SELECT 1 FROM public.igi_batches`,
    `   WHERE model_id = ${model(b.serial)} AND reference = ${q(b.reference)});`,
  );
}
say('');

say(
  '-- The 23 movements. Nine of them carry a total with no models — those are the',
  '-- certificates IGI issued between 16 June and 28 July without recording which',
  '-- model they belonged to. They stay visible instead of being absorbed.',
  'INSERT INTO public.igi_visits (visit_no, visit_date, status, date_suspect, unattributed_total, closed_at)',
  'VALUES',
);
say(seed.visits.map((v) => `  (${[
  v.visit_no, q(v.visit_date), q(v.status), v.date_suspect ? 'true' : 'false',
  n(v.unattributed_total), `${q(v.visit_date)}::date + time '12:00'`,
].join(', ')})`).join(',\n'));
say('ON CONFLICT (visit_no) DO NOTHING;', '');

const lines = [];
for (const v of seed.visits) {
  for (const l of v.lines) {
    lines.push(`  ((SELECT id FROM public.igi_visits WHERE visit_no = ${v.visit_no}), ${model(l.serial)}, ${l.qty}, ${l.qty}, ${l.qty})`);
  }
}
say(
  '-- What each movement carried, model by model.',
  'INSERT INTO public.igi_visit_lines (visit_id, model_id, qty_requested, qty_issued, qty_received)',
  'VALUES',
  lines.join(',\n'),
  'ON CONFLICT (visit_id, model_id) DO NOTHING;',
  '',
);

say(
  '-- One reading of LoveLab\'s shelf, taken from the packing-stock endpoint on',
  `-- ${SHELF_DATE}, so the screens have a shelf figure from the first minute.`,
  '-- The nightly job writes a fresher one and the screens use the newest.',
  'INSERT INTO public.igi_shelf_snapshots (snapshot_date, description, total_pcs, model_id)',
  `SELECT ${q(SHELF_DATE)}::date, v.description, v.total_pcs, d.model_id`,
  '  FROM (VALUES',
);
say(live.data.map((l) => `    (${q(l.description)}, ${Number(l.total_pcs)})`).join(',\n'));
say(
  '  ) AS v(description, total_pcs)',
  '  LEFT JOIN public.igi_descriptions d ON d.description = v.description',
  'ON CONFLICT (snapshot_date, description) DO NOTHING;',
  '',
);

// ── 3. The check ────────────────────────────────────────────────────────────
// The check is scoped to the rows THIS file loads. Once the module is in use
// there are newer movements, batches, descriptions and levels on top of them
// (Sam's database, 10 Sept 2026: 85 more issued than the opening file), and a
// re-run must pass through those untouched rather than refuse to run.
const seedSerials = seed.models.filter((m) => m.serial).map((m) => q(m.serial)).join(', ');
const seedWaiting = seed.models.filter((m) => !m.serial).map((m) => `(${q(m.name)}, ${n(m.carat)})`).join(', ');
const seedRefs = [...new Set(seed.batches.map((b) => b.reference))].map(q).join(', ');
const seedDescs = seed.descriptions.map((d) => q(d.description)).join(', ');
const maxVisit = Math.max(...seed.visits.map((v) => v.visit_no));
const openingLines = `public.igi_visit_lines l JOIN public.igi_visits v ON v.id = l.visit_id WHERE v.visit_no <= ${maxVisit}`;

// [label, sql, expected, comparison]. '=' unless a later human action may
// legitimately move the figure in one direction (linking more descriptions).
const EXPECTED = [
  ['models in use', `SELECT count(*) FROM public.igi_models WHERE state = 'in_use' AND serial IN (${seedSerials})`, 61],
  ['reserved serials', `SELECT count(*) FROM public.igi_models WHERE state = 'reserved' AND serial IN (${seedSerials})`, 15],
  ['models awaiting a serial (or since numbered)', `SELECT count(*) FROM public.igi_models WHERE (name, carat) IN (${seedWaiting})`, 3],
  ['certificates ordered', `SELECT coalesce(sum(qty), 0) FROM public.igi_batches WHERE reference IN (${seedRefs})`, 62999],
  ['issued with a model', `SELECT coalesce(sum(l.qty_issued), 0) FROM ${openingLines}`, 3778],
  ['issued with no model', `SELECT coalesce(sum(unattributed_total), 0) FROM public.igi_visits WHERE visit_no <= ${maxVisit}`, 3245],
  ['unissued at IGI',
    `SELECT (SELECT coalesce(sum(qty), 0) FROM public.igi_batches WHERE reference IN (${seedRefs}))`
    + ` - (SELECT coalesce(sum(l.qty_issued), 0) FROM ${openingLines})`, 59221],
  ['movements', `SELECT count(*) FROM public.igi_visits WHERE visit_no <= ${maxVisit}`, 23],
  ['movements with a mistyped date', `SELECT count(*) FROM public.igi_visits WHERE date_suspect AND visit_no <= ${maxVisit}`, 4],
  ['descriptions classified', `SELECT count(*) FROM public.igi_descriptions WHERE description IN (${seedDescs})`, 116],
  ['descriptions linked to a model', `SELECT count(*) FROM public.igi_descriptions WHERE model_id IS NOT NULL AND description IN (${seedDescs})`, 26, '>='],
  ['certificates on the shelf',
    `SELECT coalesce(sum(total_pcs), 0) FROM public.igi_shelf_snapshots WHERE model_id IS NOT NULL AND snapshot_date = ${q(SHELF_DATE)}`, 3504],
];

say(
  '-- ─── 3 of 3 · The check ────────────────────────────────────────────────',
  '--',
  '-- An opening balance that is quietly wrong would be inherited by every screen',
  '-- and every invoice built on top of it, so this stops rather than warns.',
  '',
  'DO $check$',
  'DECLARE',
  '  v_actual bigint;',
  'BEGIN',
);
for (const [label, sql, expected, cmp = '='] of EXPECTED) {
  const bad = cmp === '>=' ? '<' : '<>';
  const word = cmp === '>=' ? 'at least' : 'expected';
  say(
    `  ${sql} INTO v_actual;`,
    `  IF v_actual ${bad} ${expected} THEN`,
    `    RAISE EXCEPTION '% is %, ${word} % — nothing has been saved', ${q(label)}, v_actual, ${expected};`,
    '  END IF;',
    `  RAISE NOTICE '  ok  % = %', rpad(${q(label)}, 44), v_actual;`,
  );
}
say(
  "  RAISE NOTICE '';",
  "  RAISE NOTICE 'IGI: ALL FIGURES MATCH';",
  'END $check$;',
  '',
  'COMMIT;',
  '',
);

const sql = out.join('\n');
writeFileSync(resolve(ROOT, 'database-migrations/igi-switch-on.sql'), sql);
console.log(
  `Wrote database-migrations/igi-switch-on.sql — ${sql.split('\n').length} lines, `
  + `${seed.models.length} models, ${seed.descriptions.length} descriptions, `
  + `${seed.visits.length} movements, ${live.data.length} shelf lines.`,
);

// The same renames on their own, for a database that was switched on before
// the names changed: a short paste rather than the whole file again.
const namesSql = [
  `-- Model names as LoveLab write them (${renames.as_of}).`,
  '-- Generated by scripts/build-igi-switch-on.mjs from lib/igi/modelRenames.json.',
  '--',
  '-- Paste into the Supabase SQL editor and run. Only rows still carrying the',
  '-- earlier name are touched; a name edited since on the Models screen stays.',
  '-- Safe to run twice. The switch-on file carries the same block, so a fresh',
  '-- database does not need this.',
  '',
  'BEGIN;',
  '',
  ...renames.renames.map((r) => `UPDATE public.igi_models SET name = ${q(r.to)} WHERE serial = ${q(r.serial)} AND name = ${q(r.from)};`),
  '',
  'DO $names$',
  'DECLARE v_left bigint;',
  'BEGIN',
  `  SELECT count(*) INTO v_left FROM (VALUES ${renames.renames.map((r) => `(${q(r.serial)}, ${q(r.from)})`).join(', ')}) AS old(serial, name)`,
  '   WHERE EXISTS (SELECT 1 FROM public.igi_models m WHERE m.serial = old.serial AND m.name = old.name);',
  "  RAISE NOTICE 'IGI: % of % models still carry an old name', v_left, " + renames.renames.length + ';',
  'END $names$;',
  '',
  'COMMIT;',
  '',
].join('\n');
writeFileSync(resolve(ROOT, 'database-migrations/igi-model-names.sql'), namesSql);
console.log(`Wrote database-migrations/igi-model-names.sql — ${renames.renames.length} renames.`);
